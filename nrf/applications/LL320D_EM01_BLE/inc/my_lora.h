#ifndef MY_LORA_H
#define MY_LORA_H

#define MY_LORA_MAX_PAYLOAD_LENGTH 70U

/*********************************************************************
**函数名称:  my_lora_init
**入口参数:  tid -- 指向线程 ID 变量的指针
**出口参数:  tid -- 返回 LoRa 线程 ID
**函数功能:  初始化 LoRaWAN 消息队列并启动 LoRa 线程
**返 回 值:  0 表示成功，负值表示初始化失败
*********************************************************************/
int my_lora_init(k_tid_t *tid);

/*********************************************************************
**函数名称:  my_lora_send_payload
**入口参数:  payload -- LoRaWAN 应用载荷指针
**           payload_length -- 应用载荷长度，范围为 1..MY_LORA_MAX_PAYLOAD_LENGTH
**出口参数:  无
**函数功能:  发送一条 LoRaWAN 应用上行数据
**返 回 值:  0 表示提交成功，负值表示参数、状态或 Modem-E 错误
*********************************************************************/
int my_lora_send_payload(const uint8_t* payload, uint8_t payload_length);

#endif
